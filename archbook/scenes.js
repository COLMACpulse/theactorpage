  const words = s => String(s || '').toLowerCase().replace(/[^a-z0-9' ]+/g, ' ').split(/\s+/).filter(w => w.length > 2);
  const root5 = w => w.slice(0, 5);
  /* Rank the library against what the shoot list says you're missing. Whole tags
     ("blue collar") count most, then word roots ("authoritative" finds "authority"). */
  function suggest(text, n) {
    const ws = words(text), t = ' ' + ws.join(' ') + ' ', roots = new Set(ws.map(root5));
    const scored = S.map((p, k) => {
      let sc = 0;
      p.tags.forEach(tag => {
        if (t.includes(' ' + tag + ' ') || t.includes(' ' + tag + 's ')) sc += tag.includes(' ') ? 4 : 3;
        else if (!tag.includes(' ') && tag.length >= 5 && roots.has(root5(tag))) sc += 2;
      });
      if (ws.some(w => w.length > 3 && p.you.toLowerCase().includes(w))) sc += 3;
      return { p, sc, k };
    }).sort((a, b) => b.sc - a.sc || a.k - b.k);
    const hits = scored.filter(x => x.sc > 0).length;
    /* best matches first, then the rest of the library, so "Another" never runs dry */
    return { matched: hits > 0, hits, list: scored.map(x => x.p).slice(0, n || S.length) };
  }
  /* The starting page for Writer's Blockage: the premise as notes, the place, the first image. No dialogue. */
  function fountain(p, wantText) {
    return [
      'Title: ' + p.title, '',
      '[[From your ARCHBOOK shoot list: "' + String(wantText || '').replace(/"/g, "'") + '"]]', '',
      '[[YOU: ' + p.you + '. ACROSS FROM YOU: ' + p.them + '.]]', '',
      '[[' + p.situation + ']]', '',
      '[[YOU WANT: ' + p.want + ' IN THE WAY: ' + p.way + ']]', '',
      p.where, '',
      p.start, ''
    ].join('\n');
  }
