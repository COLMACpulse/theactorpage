/* DELIVERY: how the office wants the tape, from their words. Made-up instructions.  node shared/test_delivery.js */
const D=require('./delivery.js');
let pass=0,fail=0; const ok=(n,c,x)=>{ if(c){pass++;console.log('PASS',n)}else{fail++;console.log('FAIL',n,x===undefined?'':JSON.stringify(x))} };
let d=D.read('Please submit both scenes in one file. Slate at the end with your name, height and location. Files must be under 100MB.');
ok('one file, slate at the end, under 100 MB', d.mode==='SLATE_LAST'&&d.files==='one'&&d.slate==='last'&&d.maxMB===100, d);
ok('each with the sentence it came from', d.why.length===3&&/both scenes in one file/.test(d.why[0].quote)&&/Slate at the end/.test(d.why[1].quote)&&/under 100MB/.test(d.why[2].quote), d.why);
ok('in plain words', D.words(d)==='One file, slate last, under 100 MB.', D.words(d));
d=D.read('Upload one file per scene. Slate as a separate file.');
ok('one file PER scene is separate files; the slate on its own', d.mode==='SEPARATE'&&d.files==='separate'&&d.slate==='separate', d);
d=D.read('Do not combine the scenes. Start with a slate.');
ok('do not combine: separate; slate at the start noted', d.mode==='SEPARATE'&&d.slate==='first'&&D.words(d)==='Separate files, slate at the start.', [d,D.words(d)]);
d=D.read('Combine all of your takes into one video and begin with your slate.');
ok('combine into one, begin with the slate: one file, slate first', d.mode==='SLATE_FIRST', d);
d=D.read('Please end with a slate stating your name and city.');
ok('only "end with a slate": one file, slate last', d.mode==='SLATE_LAST'&&!d.files, d);
d=D.read('Slate at the beginning of your first take.');
ok('only "slate at the beginning": noted, the format left to you', d.slate==='first'&&d.mode===null&&D.words(d)==='Slate at the start.', [d,D.words(d)]);
d=D.read('No slate needed, we have your info.');
ok('no slate', d.slate==='none'&&/no slate/i.test(D.words(d)), d);
d=D.read('Total file size not to exceed 1 GB. Tape must be no longer than 3 minutes.');
ok('1 GB and 3 minutes', d.maxMB===1024&&d.maxSecs===180&&D.words(d)==='Under 1 GB, no longer than 3:00.', [d,D.words(d)]);
d=D.read('Keep each scene under 2:00.\nMax file size: 250 MB');
ok('2:00 and 250 MB on separate lines', d.maxSecs===120&&d.maxMB===250, d);
d=D.read('Self tapes due Thursday 5 PM PT. Wear something casual. SAG-AFTRA. Shoots 10/12-10/14.');
ok('nothing about delivery: nothing set, nothing guessed', !d.mode&&!d.files&&!d.slate&&!d.maxMB&&!d.maxSecs&&D.words(d)==='', d);
d=D.read('The role is a 2 minute walk from the station. Rate is $1,000.');
ok('a number that is not a limit is not read as one', !d.maxSecs&&!d.maxMB, d);
ok('no em dashes in the words', !/—/.test(D.words(D.read('one file, slate at the end, under 50 MB'))));
console.log(pass+' passed, '+fail+' failed'); process.exit(fail?1:0);
